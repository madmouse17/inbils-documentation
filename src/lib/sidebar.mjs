// The Starlight sidebar. Page labels come from each page's own title (so they follow the language); the group
// labels are written here in both languages. The user guides are built from src/data/guides.json.
import { readFileSync } from 'node:fs';

const guides = JSON.parse(readFileSync(new URL('../data/guides.json', import.meta.url), 'utf8'));

const pages = (dir, slugs) => slugs.map((slug) => ({ slug: `docs/${dir}/${slug}` }));

const guideGroup = (key, guide) => ({
  label: guide.title.en,
  translations: { id: guide.title.id },
  collapsed: true,
  items: [
    { slug: `docs/guides/${key}` },
    ...guide.chapters.map((chapter) =>
      guide.mode === 'section'
        ? {
            label: chapter.title.en,
            translations: { id: chapter.title.id },
            collapsed: true,
            items: chapter.sections.map((section) => ({
              slug: `docs/guides/${key}/${chapter.slug}/${section.slug}`,
            })),
          }
        : { slug: `docs/guides/${key}/${chapter.slug}` },
    ),
  ],
});

